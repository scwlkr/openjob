import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

// docs/brand is authoritative. Runtime copies are generated, never edited.
const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check")) {
  throw new Error("Usage: node scripts/brand-assets.mjs [--check]");
}
const source = (path) => readFile(resolve(root, "docs/brand", path));
const outputs = new Map();
const put = (path, value) => outputs.set(path, Buffer.from(value));
const css = (await source("tokens.css")).toString();
const declarations = (body) => Object.fromEntries(
  [...body.matchAll(/--oj-([\w-]+):\s*([^;]+);/gu)].map((match) => [match[1], match[2]]),
);
const light = declarations(css.match(/\.openjob-brand \{([^}]+)\}/u)[1]);
const dark = { ...light, ...declarations(css.match(/\.openjob-brand \[data-theme="dark"\] \{([^}]+)\}/u)[1]) };
const value = (key, tokens) => {
  const reference = tokens[key]?.match(/^var\(--oj-([\w-]+)\)$/u);
  if (reference) return value(reference[1], tokens);
  if (!/^#[\da-f]{6}$/iu.test(tokens[key])) throw new Error(`Invalid color: ${key}`);
  return tokens[key];
};
const svgNames = [
  "mark", "mark-reverse", "mark-small", "mark-mono", "mark-mono-reverse",
  "wordmark", "wordmark-reverse", "lockup", "lockup-reverse", "app-icon", "social-card",
];
const fontNames = ["Inter-Regular.ttf", "Inter-SemiBold.ttf", "Inter-Bold.ttf", "LICENSE.txt"];
const inputPaths = [
  ...svgNames.map((name) => `docs/brand/assets/openjob-${name}.svg`),
  ...fontNames.map((name) => `docs/brand/fonts/${name}`),
  "docs/brand/fonts/InterVariable.woff2", "docs/brand/tokens.css",
  "docs/brand/generate_assets.py", "scripts/brand-assets.mjs",
].sort();
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const byPath = ([left], [right]) => left < right ? -1 : left > right ? 1 : 0;
const sourceHash = digest(JSON.stringify(await Promise.all(inputPaths.map(async (path) =>
  [path, digest(await readFile(resolve(root, path)))],
))));
const manifestPath = resolve(root, "docs/brand/generated-assets.json");
if (check) {
  let manifest;
  try { manifest = JSON.parse(await readFile(manifestPath, "utf8")); }
  catch { console.error("Missing brand asset manifest; run npm run brand:assets."); process.exit(1); }
  const stale = [];
  if (manifest.schemaVersion !== 1 || manifest.sourceHash !== sourceHash) stale.push("source/generator fingerprint");
  for (const [path, expected] of Object.entries(manifest.outputs ?? {}).sort(byPath)) {
    let current;
    try { current = await readFile(resolve(root, path)); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    if (!current || digest(current) !== expected) stale.push(path);
  }
  if (!Object.keys(manifest.outputs ?? {}).length) stale.push("empty output manifest");
  if (stale.length) console.error(`Stale brand assets; run npm run brand:assets:\n${stale.join("\n")}`);
  else console.log(`Checked ${Object.keys(manifest.outputs).length} brand assets and source/generator hashes.`);
  process.exit(stale.length ? 1 : 0);
}
const svgs = Object.fromEntries(await Promise.all(svgNames.map(async (name) =>
  [name, (await source(`assets/openjob-${name}.svg`)).toString()],
)));
const inner = (svg) => svg.replace(/^[\s\S]*?<svg\b[^>]*>/u, "")
  .replace(/<\/(?:svg)>\s*$/u, "")
  .replace(/<(title|desc)\b[^>]*>[\s\S]*?<\/\1>/gu, "").trim();
const wrap = (width, height, art) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">${art}</svg>\n`;
const paths = (svg) => [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/gu)]
  .map((match) => match[1]);
const png = (svg, size) => sharp(Buffer.from(svg))
  .resize(size, size, { fit: "contain", background: "#00000000" })
  .png({ compressionLevel: 9, adaptiveFiltering: false }).toBuffer();
const generated = "Generated by npm run brand:assets from docs/brand. Do not edit.";

// Keep historical public URLs stable while replacing all legacy artwork.
for (const [alias, canonical] of Object.entries({
  "brandmark": "mark", "brandmark-inverse": "mark-reverse",
  "brandmark-mono": "mark-mono", "brandmark-mono-inverse": "mark-mono-reverse",
  "brandmark-small": "mark-small", "wordmark": "wordmark",
  "wordmark-inverse": "wordmark-reverse", "lockup": "lockup",
  "lockup-inverse": "lockup-reverse", "app-icon": "app-icon",
  "app-icon-maskable": "app-icon",
})) put(`public/brand/openjob-${alias}.svg`, svgs[canonical]);
put("public/favicon.svg", svgs["mark-small"]);
for (const size of [192, 512]) {
  const icon = await png(svgs["app-icon"], size);
  put(`public/icon-${size}.png`, icon);
  put(`public/icon-maskable-${size}.png`, icon);
}
put("public/apple-touch-icon.png", await png(svgs["app-icon"], 180));
put("public/favicon.png", await png(svgs["mark-small"], 64));

// ICO directory entries contain real PNG payloads at all three small sizes.
const icoImages = await Promise.all([16, 32, 64].map(async (size) => ({
  size, data: await png(svgs["mark-small"], size),
})));
const icoHeader = Buffer.alloc(6 + 16 * icoImages.length);
icoHeader.writeUInt16LE(1, 2);
icoHeader.writeUInt16LE(icoImages.length, 4);
let offset = icoHeader.length;
for (const [index, { size, data }] of icoImages.entries()) {
  const entry = 6 + index * 16;
  icoHeader[entry] = size;
  icoHeader[entry + 1] = size;
  icoHeader.writeUInt16LE(1, entry + 4);
  icoHeader.writeUInt16LE(32, entry + 6);
  icoHeader.writeUInt32LE(data.length, entry + 8);
  icoHeader.writeUInt32LE(offset, entry + 12);
  offset += data.length;
}
put("public/favicon.ico", Buffer.concat([icoHeader, ...icoImages.map(({ data }) => data)]));

// Android's safe circle is smaller than the PWA maskable safe circle.
// The 3x mark fits within its central 66/108 diameter at 512 px.
const androidMark = (art) => wrap(512, 512,
  `<g transform="translate(130 136) scale(3)">${art}</g>`);
put("public/brand/android-foreground.png", await png(androidMark(inner(svgs["mark-reverse"])), 512));
put("public/brand/android-monochrome.png", await png(androidMark(inner(svgs["mark-mono-reverse"])), 512));
for (const [name, variant] of [["splash-mark", "mark"], ["splash-mark-reverse", "mark-reverse"]]) {
  put(`public/brand/${name}.png`, await png(wrap(512, 512,
    `<g transform="translate(88 96) scale(4)">${inner(svgs[variant])}</g>`), 512));
}

// Every glyph is an SVG path; rasterization never looks up fonts at runtime.
put("public/og.png", await sharp(Buffer.from(svgs["social-card"]))
  .png({ compressionLevel: 9, adaptiveFiltering: false }).toBuffer());

put("public/site.webmanifest", JSON.stringify({
  id: "/", name: "OpenJob", short_name: "OpenJob",
  description: "Clear space. Focused work.", start_url: "/", scope: "/",
  display: "standalone", background_color: light.chalk, theme_color: light.cobalt,
  icons: ["any", "maskable"].flatMap((purpose) => [192, 512].map((size) => ({
    src: `/icon-${purpose === "maskable" ? "maskable-" : ""}${size}.png`,
    sizes: `${size}x${size}`, type: "image/png", purpose,
  }))),
}, null, 2) + "\n");

const wordmarkWidth = Number(svgs.wordmark.match(/viewBox="0 0 ([\d.]+) /u)[1]);
const [markBackPath, markFrontPath] = paths(svgs.mark);
put("native/src/brand-assets.ts", `// ${generated}\n` +
  `export const wordmarkWidth = ${wordmarkWidth};\n` +
  `export const wordmarkPaths = ${JSON.stringify(paths(svgs.wordmark), null, 2)};\n` +
  `export const markFrontPath = ${JSON.stringify(markFrontPath)};\n` +
  `export const markBackPath = ${JSON.stringify(markBackPath)};\n`);

const camelCase = (key) => key.replace(/-([a-z])/gu, (_, letter) => letter.toUpperCase());
const roles = ["surface", "panel", "text", "muted", "line", "control-line", "action",
  "action-hover", "action-text", "link", "selected", "selected-text", "focus", "positive", "positive-fill"];
const colors = (keys, tokens) => Object.fromEntries(keys.map((key) => [camelCase(key), value(key, tokens)]));
put("native/src/brand-tokens.ts", `// ${generated}\n` +
  `export const brandPalette = ${JSON.stringify(colors(["chalk", "graphite", "cobalt", "blue-gray", "sage"], light), null, 2)};\n` +
  `export const brandLight = ${JSON.stringify(colors(roles, light), null, 2)};\n` +
  `export const brandDark = ${JSON.stringify(colors(roles, dark), null, 2)};\n`);
put("app/brand-tokens.css", `/* ${generated} */\n` + css
  .replace(/^\/\*[^]*?\*\/\s*/u, "")
  .replace('url("./fonts/InterVariable.woff2")', 'url("../docs/brand/fonts/InterVariable.woff2")')
  .replace(".openjob-brand {", ":root {\n  color-scheme: light;")
  .replace('.openjob-brand[data-theme="dark"], .openjob-brand [data-theme="dark"] {',
    '@media (prefers-color-scheme: dark) {\n  :root {\n    color-scheme: dark;') + "}\n");
for (const name of fontNames) {
  put(`native/assets/fonts/${name}`, await source(`fonts/${name}`));
}

for (const [path, bytes] of outputs) {
  const filename = resolve(root, path);
  await mkdir(dirname(filename), { recursive: true });
  await writeFile(filename, bytes);
}
await writeFile(manifestPath, JSON.stringify({
  schemaVersion: 1, sourceHash,
  outputs: Object.fromEntries([...outputs].sort(byPath)
    .map(([path, bytes]) => [path, digest(bytes)])),
}, null, 2) + "\n");
console.log(`Generated ${outputs.size} brand assets from docs/brand.`);
