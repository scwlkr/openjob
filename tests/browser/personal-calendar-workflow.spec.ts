import { expect, test } from "@playwright/test";

test("Calendar opens the exact Task and source Mail while keeping unfinished editors", async ({ page, request }, testInfo) => {
  const { token } = await (await request.get("/__test/session/alex")).json();
  const command = async (input: unknown) => {
    const response = await request.post("/api/v1/workspace/commands", { headers: { authorization: `Bearer ${token}` }, data: input });
    expect(response.status()).toBe(200); return (await response.json()).data;
  };
  await command({ type: "mail.examples.add" });
  const marker = `Calendar workflow ${Date.now()}`;
  const pairs: { taskId: string; eventId: string; title: string }[] = [];
  for (const width of [1280, 390]) {
    const title = `${marker} ${width}`;
    const created = await command({ type: "task.create", title, messageId: "example-message-3" });
    const scheduled = await command({ type: "task.schedule", taskId: created.id, calendarId: "personal", start: "2027-05-10T09:00:00Z", end: "2027-05-10T09:30:00Z" });
    pairs.push({ taskId: created.id, eventId: scheduled.calendarEventId, title });
    await command({ type: "calendar.create", calendarId: "personal", title: `${title} separate block`, start: "2027-05-11T09:00:00Z", end: "2027-05-11T09:30:00Z" });
    await page.setViewportSize({ width, height: 900 });
    await page.goto("/");
    const row = page.getByTestId("task-row").filter({ hasText: title });
    await expect(row).toBeVisible();
    await page.getByLabel("New task", { exact: true }).fill(`${title} unfinished new task`);
    await row.getByRole("button", { name: "Edit title", exact: true }).click();
    await page.getByLabel("Task title", { exact: true }).fill(`${title} revised`);
    await row.getByRole("button", { name: "Schedule", exact: true }).click();
    await page.getByLabel("Start (UTC)", { exact: true }).fill("2027-05-12T11:00");
    await page.getByLabel("End (UTC)", { exact: true }).fill("2027-05-12T11:30");
    await page.getByRole("button", { name: "Calendar", exact: true }).click();
    const event = page.getByTestId("calendar-event").filter({ hasText: title }).filter({ has: page.getByRole("button", { name: "Open linked task", exact: true }) });
    const separate = page.getByTestId("calendar-event").filter({ hasText: `${title} separate block` });
    await expect(separate.getByRole("button", { name: "Open linked task", exact: true })).toHaveCount(0);
    await separate.getByRole("button", { name: "Edit block", exact: true }).click();
    await page.getByLabel("Block title", { exact: true }).fill(`${title} unfinished calendar edit`);
    await page.getByLabel("Start (UTC)", { exact: true }).fill("2027-05-13T13:00");
    await event.getByRole("button", { name: "Open linked task", exact: true }).click();
    await expect(row).toBeFocused();
    await expect(page.getByRole("status")).toContainText("Linked Task opened");
    await expect(page.getByLabel("Task title", { exact: true })).toHaveValue(`${title} revised`);
    await expect(page.getByLabel("New task", { exact: true })).toHaveValue(`${title} unfinished new task`);
    await expect(page.getByLabel("Start (UTC)", { exact: true })).toHaveValue("2027-05-12T11:00");
    await row.getByRole("checkbox").click();
    await expect(row.getByRole("checkbox")).toBeChecked();
    await row.getByRole("button", { name: "Open source mail", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Design review notes", exact: true })).toBeFocused();
    await expect(page.getByLabel("Mailbox", { exact: true })).toHaveValue("mail:example-gmail-work");
    await page.getByLabel("Reply draft", { exact: true }).fill(`${title} completed and replied`);
    await page.getByRole("button", { name: "Save draft", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("No message sent");
    await page.getByRole("button", { name: "Calendar", exact: true }).click();
    await expect(page.getByLabel("Block title", { exact: true })).toHaveValue(`${title} unfinished calendar edit`);
    await expect(page.getByLabel("Start (UTC)", { exact: true })).toHaveValue("2027-05-13T13:00");
    await expect(page.getByText(`Editing “${title} separate block”. The block stays on its original calendar.`, { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Cancel edit", exact: true }).click();
    const day = await page.getByLabel("Calendar date", { exact: true }).inputValue();
    await expect(page.getByLabel("Start (UTC)", { exact: true })).toHaveValue(`${day}T14:00`);
    await expect(page.getByLabel("End (UTC)", { exact: true })).toHaveValue(`${day}T14:30`);
    await event.getByRole("button", { name: "Open linked task", exact: true }).click();
    await expect(row.getByRole("checkbox")).toBeChecked();
    await page.getByRole("button", { name: "Save title", exact: true }).click();
    await page.getByRole("button", { name: "Save schedule", exact: true }).click();
    await page.getByRole("button", { name: "Calendar", exact: true }).click();
    await expect(event).toContainText(`${title} revised`);
    await expect(event).toContainText("May 12, 2027");
    await page.screenshot({ path: testInfo.outputPath(`calendar-linked-work-${width}.png`), fullPage: true });
    await page.reload();
    await expect(row.getByRole("checkbox")).toBeChecked();
    await expect(page.getByLabel("New task", { exact: true })).toHaveValue("");
  }
  await page.route("**/api/v1/workspace/snapshot", async route => {
    const response = await route.fetch(); const body = await response.json();
    body.data.tasks = body.data.tasks.filter((task: { id: string }) => task.id !== pairs[0].taskId);
    body.data.tasks.find((task: { id: string }) => task.id === pairs[1].taskId).calendarEventId = "mismatched-event";
    await route.fulfill({ response, json: body });
  });
  await page.reload(); await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Calendar", exact: true }).click();
  for (const pair of pairs) await expect(page.getByTestId("calendar-event").filter({ hasText: `${pair.title} revised` }).getByRole("button", { name: "Open linked task", exact: true })).toHaveCount(0);
  await page.unroute("**/api/v1/workspace/snapshot");
  await page.getByLabel("Block title", { exact: true }).fill("Do not carry this across owners");
  await page.getByLabel("Test identity", { exact: true }).selectOption("sam");
  await expect(page.getByLabel("New task", { exact: true })).toHaveValue("");
  await expect(page.getByTestId("task-row").filter({ hasText: marker })).toHaveCount(0);
  await page.getByRole("button", { name: "Calendar", exact: true }).click();
  await expect(page.getByLabel("Block title", { exact: true })).toHaveValue("");
});
