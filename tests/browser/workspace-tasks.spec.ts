import { expect, test } from "@playwright/test";

test("mail-linked tasks edit, reschedule, unschedule and delete with calendar consistency", async ({ page }, testInfo) => {
  const title = `Task lifecycle ${Date.now()}`;
  await page.goto("/workspace");
  await page.getByTestId("mail-row").filter({ hasText: "Design review notes" }).click();
  await page.getByRole("button", { name: "Create task from mail", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Private task created");
  await page.getByRole("button", { name: /^Tasks/ }).click();
  const sourceTask = page.getByTestId("task-row").filter({ hasText: "Design review notes" }).last();
  await sourceTask.getByRole("button", { name: "Open source mail", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Design review notes", exact: true })).toBeFocused();
  await expect(page.getByLabel("Mailbox", { exact: true })).toHaveValue("alex_outlook");
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await sourceTask.getByRole("button", { name: "Edit title", exact: true }).click();
  await page.getByLabel("Task title", { exact: true }).fill(title);
  await page.getByRole("button", { name: "Save title", exact: true }).click();
  let row = page.getByTestId("task-row").filter({ hasText: title });
  await expect(row).toContainText("From private mail");
  await row.getByRole("button", { name: "Edit title", exact: true }).click();
  await page.getByLabel("Task title", { exact: true }).fill("Discard this title change");
  await page.getByRole("button", { name: "Cancel edit", exact: true }).click();
  await expect(row).toBeVisible();
  await expect(page.getByText("Discard this title change", { exact: true })).toHaveCount(0);
  await row.getByRole("button", { name: "Schedule", exact: true }).click();
  await page.getByLabel("Calendar", { exact: true }).selectOption("alex_work");
  await page.getByLabel("Start (UTC)", { exact: true }).fill("2027-02-04T10:00");
  await page.getByLabel("End (UTC)", { exact: true }).fill("2027-02-04T10:30");
  await page.getByRole("button", { name: "Save schedule", exact: true }).click();
  await expect(row).toContainText("Work");
  await row.getByRole("checkbox").click();
  await expect(row.getByRole("checkbox")).toBeChecked();
  await row.getByRole("button", { name: "Schedule", exact: true }).click();
  await expect(page.getByLabel("Calendar", { exact: true })).toHaveValue("alex_work");
  await expect(page.getByLabel("Start (UTC)", { exact: true })).toHaveValue("2027-02-04T10:00");
  await expect(page.getByLabel("End (UTC)", { exact: true })).toHaveValue("2027-02-04T10:30");
  await page.getByLabel("Calendar", { exact: true }).selectOption("alex_personal");
  await page.getByLabel("Start (UTC)", { exact: true }).fill("2027-02-05T11:00");
  await page.getByLabel("End (UTC)", { exact: true }).fill("2027-02-05T11:30");
  await page.getByRole("button", { name: "Save schedule", exact: true }).click();
  await expect(row).toContainText("Personal");
  await row.getByRole("button", { name: "Edit title", exact: true }).click();
  await page.getByLabel("Task title", { exact: true }).fill(`${title} revised`);
  await page.getByRole("button", { name: "Save title", exact: true }).click();
  row = page.getByTestId("task-row").filter({ hasText: `${title} revised` });
  await expect(row.getByRole("checkbox")).toBeChecked();
  await page.getByRole("button", { name: /^Calendar/ }).click();
  const event = page.getByTestId("calendar-event").filter({ hasText: `${title} revised` });
  await expect(event).toHaveCount(1);
  await expect(event).toContainText("linked task");
  await expect(event).toContainText("Feb 5, 2027");
  await expect(event).toContainText("Personal");
  await event.getByRole("button", { name: "Open linked task", exact: true }).click();
  await expect(row).toBeFocused();
  await row.getByRole("button", { name: "Unschedule", exact: true }).click();
  await expect(row).toContainText("Unscheduled");
  await page.getByRole("button", { name: /^Calendar/ }).click();
  await expect(page.getByTestId("calendar-event").filter({ hasText: title })).toHaveCount(0);
  await page.reload();
  await expect(page.getByTestId("mail-row").first()).toBeVisible();
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await expect(row).toContainText("Unscheduled");
  await expect(row.getByRole("checkbox")).toBeChecked();
  await row.getByRole("button", { name: "Schedule", exact: true }).click();
  const today = await page.evaluate(() => new Date().toISOString().slice(0, 10));
  await expect(page.getByLabel("Start (UTC)", { exact: true })).toHaveValue(`${today}T14:00`);
  await page.getByRole("button", { name: "Save schedule", exact: true }).click();
  await expect(row.getByRole("button", { name: "Unschedule", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("workspace-task-lifecycle.png"), fullPage: true });
  page.once("dialog", async (dialog) => { expect(dialog.message()).toContain("linked calendar block"); expect(dialog.message()).toContain("Source mail is kept"); await dialog.accept(); });
  await row.getByRole("button", { name: "Delete task", exact: true }).click();
  await expect(row).toHaveCount(0);
  await page.getByRole("button", { name: /^Calendar/ }).click();
  await expect(page.getByTestId("calendar-event").filter({ hasText: title })).toHaveCount(0);
  await page.getByRole("button", { name: /^Mail/ }).click();
  await expect(page.getByTestId("mail-row").filter({ hasText: "Design review notes" })).toBeVisible();
  await page.reload();
  await expect(page.getByTestId("mail-row").first()).toBeVisible();
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await expect(row).toHaveCount(0);
});

test("task deletion can be cancelled on a phone without losing the task", async ({ page }, testInfo) => {
  const title = `Phone keep task ${Date.now()}`;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/workspace");
  await expect(page.getByTestId("mail-row").first()).toBeVisible();
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await page.getByLabel("New task", { exact: true }).fill(title);
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  const row = page.getByTestId("task-row").filter({ hasText: title });
  await expect(row).toBeVisible();
  page.once("dialog", (dialog) => dialog.dismiss());
  await row.getByRole("button", { name: "Delete task", exact: true }).click();
  await expect(row).toBeVisible();
  await page.reload();
  await expect(page.getByTestId("mail-row").first()).toBeVisible();
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await expect(row).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("workspace-tasks-phone.png"), fullPage: true });
});
