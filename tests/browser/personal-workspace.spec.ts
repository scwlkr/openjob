import { expect, test } from "@playwright/test";

test("authenticated personal tasks and calendar persist through the real bearer API", async ({ page }, testInfo) => {
  const marker = `Personal task ${Date.now()}`;
  const headers: { bearer: boolean; fixture: boolean }[] = [];
  page.on("request", (request) => {
    if (request.url().includes("/api/v1/workspace/")) headers.push({ bearer: request.headers().authorization?.startsWith("Bearer ") || false, fixture: Object.keys(request.headers()).some((name) => name.startsWith("x-openjob-fixture")) });
  });
  await page.goto("/");
  await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await page.getByLabel("New task", { exact: true }).fill(marker);
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  let row = page.getByTestId("task-row").filter({ hasText: marker });
  await row.getByRole("button", { name: "Edit title", exact: true }).click();
  await page.getByLabel("Task title", { exact: true }).fill(`${marker} edited`);
  await page.getByRole("button", { name: "Save title", exact: true }).click();
  row = page.getByTestId("task-row").filter({ hasText: `${marker} edited` });
  await row.getByRole("button", { name: "Schedule", exact: true }).click();
  await page.getByLabel("Start (UTC)", { exact: true }).fill("2027-03-02T10:00");
  await page.getByLabel("End (UTC)", { exact: true }).fill("2027-03-02T10:30");
  await page.getByRole("button", { name: "Save schedule", exact: true }).click();
  await row.getByRole("checkbox").click();
  await expect(row.getByRole("checkbox")).toBeChecked();
  await page.getByRole("button", { name: "Calendar", exact: true }).click();
  await expect(page.getByTestId("calendar-event").filter({ hasText: `${marker} edited` })).toContainText("linked task");
  await page.screenshot({ path: testInfo.outputPath("personal-workspace-calendar.png"), fullPage: true });
  await page.reload();
  await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await expect(row.getByRole("checkbox")).toBeChecked();
  await expect(row).toContainText("2027");
  await page.screenshot({ path: testInfo.outputPath("personal-workspace-tasks.png"), fullPage: true });
  await page.getByRole("button", { name: "Mail preview", exact: true }).click();
  await expect(page.getByText(/Synthetic Mail preview/)).toBeVisible();
  await page.getByRole("button", { name: /Launch checklist for Friday/ }).click();
  await page.getByRole("button", { name: "Create personal task from example", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("no mailbox link was saved");
  const commandRequests = await page.request.get("/api/v1/workspace/snapshot");
  expect(commandRequests.status()).toBe(401); // This separate HTTP client has no authenticated session.
  expect(headers.length).toBeGreaterThan(4);
  expect(headers.every((entry) => entry.bearer && !entry.fixture)).toBe(true);
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page.getByRole("button", { name: "Continue with Google", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Continue with Google", exact: true }).click();
  await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await expect.poll(() => page.evaluate(() => window.personalWorkspaceFixture.disposedProofs)).toBe(1);
});

test("identity swaps clear edits and reject deferred old-session writes and reads", async ({ page }) => {
  const marker = `Boundary task ${Date.now()}`;
  let posts = 0;
  page.on("request", (request) => { if (request.method() === "POST" && request.url().includes("/api/v1/workspace/commands")) posts += 1; });
  await page.goto("/");
  await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await page.getByLabel("New task", { exact: true }).fill(marker);
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  const row = page.getByTestId("task-row").filter({ hasText: marker });
  await expect(row).toBeVisible();
  await page.evaluate(() => window.personalWorkspaceFixture.deferNextToken());
  await page.getByLabel("New task", { exact: true }).fill(`${marker} deferred`);
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  await expect.poll(() => page.evaluate(() => window.personalWorkspaceFixture.tokenIsWaiting)).toBe(true);
  const before = posts;
  await page.getByLabel("Test identity", { exact: true }).selectOption("sam");
  await expect(page.getByLabel("New task", { exact: true })).toHaveValue("");
  await expect(row).toHaveCount(0);
  await page.evaluate(() => window.personalWorkspaceFixture.releaseToken());
  await page.getByLabel("Test identity", { exact: true }).selectOption("alex");
  await expect(row).toBeVisible();
  await expect(page.getByTestId("task-row").filter({ hasText: `${marker} deferred` })).toHaveCount(0);
  expect(posts).toBe(before);
  await row.getByRole("button", { name: "Edit title", exact: true }).click();
  await page.getByLabel("Task title", { exact: true }).fill("Unsaved previous owner edit");
  await page.evaluate(() => window.personalWorkspaceFixture.deferNextToken());
  await page.getByRole("button", { name: "Refresh", exact: true }).click();
  await expect.poll(() => page.evaluate(() => window.personalWorkspaceFixture.tokenIsWaiting)).toBe(true);
  await page.getByLabel("Test identity", { exact: true }).selectOption("sam");
  await expect(row).toHaveCount(0);
  await page.evaluate(() => window.personalWorkspaceFixture.releaseToken());
  await expect(page.getByLabel("New task", { exact: true })).toHaveValue("");
  await expect(page.getByLabel("Task title", { exact: true })).toHaveCount(0);
  await expect(row).toHaveCount(0);
});

test("human agent controls show effective scopes, isolate owners and revoke real API access", async ({ page, request }, testInfo) => {
  const name = `Personal helper ${Date.now()}`;
  const owner = await (await request.get("/__test/session/alex")).json() as { token: string };
  const issuedResponse = await request.post("/api/v1/workspace/agent-grants", {
    headers: { authorization: `Bearer ${owner.token}` },
    data: { name, scopes: ["tasks:read", "tasks:write"], resourceIds: ["tasks:personal"] },
  });
  expect(issuedResponse.status()).toBe(201);
  const issued = (await issuedResponse.json() as { data: { agent: { id: string }; token: string } }).data;
  const acted = await request.post("/api/v1/workspace/commands", { headers: { authorization: `Bearer ${issued.token}` }, data: { type: "task.create", title: `${name} task` } });
  expect(acted.status()).toBe(200);
  expect((await request.get("/api/v1/workspace/agent-grants", { headers: { authorization: `Bearer ${issued.token}` } })).status()).toBe(401);
  await page.goto("/");
  await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await expect(page.getByTestId("task-row").filter({ hasText: `${name} task` })).toBeVisible();
  await page.getByText("Recent activity", { exact: true }).click();
  await expect(page.getByTestId("personal-activity").filter({ hasText: issued.agent.id })).toContainText("task.create");
  await page.getByRole("button", { name: "Agents", exact: true }).click();
  const row = page.getByTestId("personal-agent-row").filter({ hasText: name });
  await expect(row).toContainText("Effective scopes: tasks:read, tasks:write");
  await expect(row).toContainText("Effective resources: tasks:personal");
  expect((await page.content()).includes(issued.token)).toBe(false);
  expect((await page.content()).includes("tokenHash")).toBe(false);
  await page.getByLabel("Test identity", { exact: true }).selectOption("sam");
  await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Agents", exact: true }).click();
  await expect(page.getByText("No personal agents have access.", { exact: false })).toBeVisible();
  await expect(row).toHaveCount(0);
  await page.getByLabel("Test identity", { exact: true }).selectOption("alex");
  await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Agents", exact: true }).click();
  await expect(row).toBeVisible();
  page.once("dialog", (dialog) => dialog.accept());
  await row.getByRole("button", { name: "Revoke access", exact: true }).click();
  await expect(row).toContainText("Revoked");
  await expect(row.getByRole("button", { name: "Revoke access", exact: true })).toBeDisabled();
  expect((await request.get("/api/v1/workspace/snapshot", { headers: { authorization: `Bearer ${issued.token}` } })).status()).toBe(401);
  await page.reload();
  await expect(page.getByLabel("New task", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Agents", exact: true }).click();
  await expect(row).toContainText("Revoked");
  await page.screenshot({ path: testInfo.outputPath("personal-workspace-agent-grants.png"), fullPage: true });
});
