import { expect, test } from "@playwright/test";

test("mail folders and case-insensitive search preserve mailbox and unsaved inputs", async ({ page }) => {
  const marker = `Navigation ${Date.now()}`;
  await page.goto("/workspace");
  await page.getByLabel("Mailbox", { exact: true }).selectOption("alex_outlook");
  await page.getByLabel("Search mail", { exact: true }).fill("DESIGN REVIEW");
  await expect(page.getByTestId("mail-row")).toHaveCount(1);
  await expect(page.getByTestId("mail-row")).toContainText("Design review notes");
  await expect(page.getByLabel("Mailbox", { exact: true })).toHaveValue("alex_outlook");
  await page.getByLabel("Search mail", { exact: true }).fill("STUDIO BOOKING");
  await expect(page.getByTestId("mail-row")).toHaveCount(0);
  await expect(page.getByText("No messages match this search in the selected mailbox.", { exact: true })).toBeVisible();
  await page.getByLabel("Search mail", { exact: true }).fill("SIMPLER NAVIGATION");
  await page.getByTestId("mail-row").click();
  await page.getByLabel("Reply draft", { exact: true }).fill(`${marker} unsaved reply`);
  await page.getByRole("button", { name: "Drafts", exact: true }).click();
  await expect(page.getByRole("button", { name: "Drafts", exact: true })).toHaveAttribute("aria-current", "page");
  await page.getByRole("button", { name: "Inbox", exact: true }).click();
  await expect(page.getByLabel("Reply draft", { exact: true })).toHaveValue(`${marker} unsaved reply`);

  await page.getByRole("button", { name: "Compose draft", exact: true }).click();
  await page.getByLabel("From mailbox").selectOption("alex_outlook");
  await page.getByLabel("To", { exact: true }).fill("navigation@example.invalid");
  await page.getByLabel("Subject", { exact: true }).fill(marker);
  await page.getByLabel("Message", { exact: true }).fill("Preserved composer body");
  await page.getByRole("button", { name: "Simulated Sent", exact: true }).click();
  await expect(page.getByLabel("Message", { exact: true })).toHaveValue("Preserved composer body");
  await page.getByRole("button", { name: "Drafts", exact: true }).click();
  await expect(page.getByLabel("To", { exact: true })).toHaveValue("navigation@example.invalid");
  await expect(page.getByLabel("Subject", { exact: true })).toHaveValue(marker);
  await page.getByRole("button", { name: "Save new draft", exact: true }).click();
  await page.getByLabel("Search mail", { exact: true }).fill(marker.toUpperCase());
  const saved = page.getByTestId("saved-draft").filter({ hasText: marker });
  await expect(saved).toContainText("Preserved composer body");
  await page.getByLabel("Search mail", { exact: true }).fill("NAVIGATION@EXAMPLE.INVALID");
  await expect(saved).toBeVisible();
  await expect(page.getByLabel("Mailbox", { exact: true })).toHaveValue("alex_outlook");
  await saved.getByRole("button", { name: "Simulate send", exact: true }).click();
  await expect(page.getByText("No drafts match this search in the selected mailbox.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Simulated Sent", exact: true }).click();
  const sent = page.getByTestId("sent-message").filter({ hasText: marker });
  await expect(sent).toBeVisible();
  await expect(sent).toContainText("alex@outlook.example.invalid");
  await page.getByLabel("Mailbox", { exact: true }).selectOption("alex_gmail");
  await expect(sent).toHaveCount(0);
  await expect(page.getByText("No simulated messages match this search in the selected mailbox.", { exact: true })).toBeVisible();
  await page.getByLabel("Mailbox", { exact: true }).selectOption("alex_outlook");
  await expect(sent).toBeVisible();
  await page.getByRole("button", { name: "Inbox", exact: true }).click();
  await page.getByRole("button", { name: "Clear search", exact: true }).click();
  await expect(page.getByTestId("mail-row")).toHaveCount(1);
  await page.getByLabel("Fixture owner").selectOption("demo_sam");
  await page.getByRole("button", { name: "Simulated Sent", exact: true }).click();
  await page.getByLabel("Search mail", { exact: true }).fill(marker);
  await expect(page.getByTestId("sent-message")).toHaveCount(0);
});

test("mail folder navigation and search fit a phone", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/workspace");
  await expect(page.getByTestId("mail-row").first()).toBeVisible();
  await page.getByRole("button", { name: "Drafts", exact: true }).click();
  await expect(page.getByRole("region", { name: "Saved drafts", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Simulated Sent", exact: true }).click();
  await expect(page.getByRole("region", { name: "Simulated Sent", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Inbox", exact: true }).click();
  await page.getByLabel("Search mail", { exact: true }).fill("checklist");
  await expect(page.getByTestId("mail-row")).toHaveCount(1);
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("workspace-mail-folders-phone.png"), fullPage: true });
});
