import { expect, test } from "@playwright/test";

test("built workspace reads IMAP protocol pages, creates a private title-only Task and honors revocation", async ({ page, request }, testInfo) => {
  const token = (await (await request.get("/__test/session/alex")).json()).token;
  await page.goto("/workspace");
  await page.getByRole("button", { name: "Mail preview", exact: true }).click();
  const account = page.getByLabel("Preview account", { exact: true });
  const alex = page.getByRole("option", { name: /Mock IMAP protocol · Alex/ });
  const accountId = await alex.getAttribute("value");
  expect(accountId).toBeTruthy();
  const consent = await page.getByRole("option", { name: /Mock IMAP protocol · consent required/ }).getAttribute("value");
  const beforeConsent = await (await request.get("/__test/provider-counters")).json();
  await account.selectOption(consent!);
  await expect(page.getByTestId("provider-status")).toContainText("Mail consent required");
  await expect(page.getByTestId("provider-message")).toHaveCount(0);
  expect(await (await request.get("/__test/provider-counters")).json()).toEqual(beforeConsent);
  const loaded = page.waitForResponse(response => response.url().includes("/workspace/provider-preview") && response.url().includes(accountId!));
  await account.selectOption(accountId!);
  const preview = (await (await loaded).json()).data;
  expect(preview.mode).toBe("mock");
  expect(preview.accounts.find((item: { id: string }) => item.id === accountId)).toMatchObject({ provider: "imap", mode: "mock", status: "ready" });
  for (const secret of ["credentialRef", "accessToken", "@odata.nextLink", "graph.microsoft.com"]) expect(JSON.stringify(preview)).not.toContain(secret);
  await expect(page.getByTestId("provider-mode")).toContainText("Mock IMAP protocol · invented data · no live connection or sending");
  await expect(page.getByTestId("provider-message")).toHaveCount(2);
  await page.getByTestId("provider-message").filter({ hasText: "IMAP fixture: prepare the launch" }).click();
  const reader = page.getByRole("region", { name: "Mock IMAP message reader", exact: true });
  await expect(reader).toContainText("Invented message read through the IMAP wire mapper for alex");
  await expect(reader).toContainText("Café 日本語");
  await expect(reader).toContainText("INBOX");
  await expect(reader).toContainText("no conversation threading");
  const created = page.waitForRequest(item => item.method() === "POST" && item.url().includes("/workspace/commands"));
  await reader.getByRole("button", { name: "Create personal task from example", exact: true }).click();
  expect((await created).postDataJSON()).toEqual({ type: "task.create", title: "IMAP fixture: prepare the launch" });
  await expect(page.getByRole("status")).toContainText("no mailbox link was saved");
  const snapshot = (await (await request.get("/api/v1/workspace/snapshot", { headers: { authorization: `Bearer ${token}` } })).json()).data;
  const task = snapshot.tasks.find((item: { title: string }) => item.title === "IMAP fixture: prepare the launch");
  expect(task).toBeTruthy();
  for (const key of ["messageId", "sourceAccountId", "sourceMessageId", "sourceThreadId"]) expect(task[key]).toBeUndefined();
  await page.screenshot({ path: testInfo.outputPath("imap-mail-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 900 });
  await page.getByRole("button", { name: "Next messages", exact: true }).click();
  await expect(page.getByTestId("provider-message")).toHaveCount(1);
  await expect(page.getByTestId("provider-message")).toContainText("IMAP fixture: follow up");
  await page.getByRole("button", { name: "Previous messages", exact: true }).click();
  await expect(page.getByTestId("provider-message")).toHaveCount(2);
  await page.getByTestId("provider-message").first().click();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("imap-mail-phone.png"), fullPage: true });
  await page.getByLabel("Test identity", { exact: true }).selectOption("sam");
  await page.getByRole("button", { name: "Mail preview", exact: true }).click();
  await expect(alex).toHaveCount(0);
  await expect(page.getByRole("option", { name: /Mock IMAP protocol · Sam/ })).toHaveCount(1);
  const sam = (await (await request.get("/__test/session/sam")).json()).token;
  expect((await request.get(`/api/v1/workspace/provider-preview?accountId=${accountId}`, { headers: { authorization: `Bearer ${sam}` } })).status()).toBe(403);
  await page.getByLabel("Test identity", { exact: true }).selectOption("alex");
  await page.getByRole("button", { name: "Mail preview", exact: true }).click();
  await account.selectOption(accountId!);
  await expect(page.getByTestId("provider-message")).toHaveCount(2);
  expect((await request.post(`/__test/provider-connections/${accountId}/reset-uidvalidity`, { headers: { "x-openjob-test-control": "mock-provider" } })).status()).toBe(204);
  await page.getByRole("button", { name: "Next messages", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("Provider preview could not be loaded");
  await expect(page.getByTestId("provider-message")).toHaveCount(0);
  const recovered = page.waitForResponse(response => response.url().includes("/workspace/provider-preview") && response.url().includes(accountId!));
  await page.getByRole("button", { name: "Refresh preview", exact: true }).click();
  const afterReset = (await (await recovered).json()).data;
  expect(afterReset.messages[0].id).not.toBe(preview.messages[0].id);
  await expect(page.getByTestId("provider-message")).toHaveCount(2);
  const before = await (await request.get("/__test/provider-counters")).json();
  expect((await request.post(`/__test/provider-connections/${accountId}/revoke`, { headers: { "x-openjob-test-control": "mock-provider" } })).status()).toBe(204);
  await page.getByRole("button", { name: "Refresh preview", exact: true }).click();
  await expect(page.getByTestId("provider-status")).toContainText("Access revoked");
  await expect(page.getByTestId("provider-message")).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Next messages", exact: true })).toBeDisabled();
  expect(await (await request.get("/__test/provider-counters")).json()).toEqual(before);
});
