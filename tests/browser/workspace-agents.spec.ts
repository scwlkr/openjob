import { expect, test } from "@playwright/test";

test("simulated agent actions enforce scopes, revoke immediately and isolate owners", async ({ page }, testInfo) => {
  const unique = `Agent action ${Date.now()}`;
  await page.goto("/workspace");
  await expect(page.getByTestId("mail-row").first()).toBeVisible();
  await page.getByRole("button", { name: /^Agents/ }).click();
  await page.getByLabel("Agent name").fill(`${unique} reader`);
  await page.getByLabel("Personal tasks", { exact: true }).check();
  await page.getByRole("button", { name: "Create agent", exact: true }).click();
  const reader = page.getByTestId("agent-row").filter({ hasText: `${unique} reader` });
  await reader.getByRole("button", { name: "Inspect access" }).click();
  const inspection = page.getByRole("region", { name: "Agent access result" });
  await expect(inspection).toContainText("Effective scopes: tasks:read");
  await expect(inspection).toContainText("Effective resources: Personal tasks");
  await inspection.getByLabel("Agent task title").fill(`${unique} denied`);
  await inspection.getByRole("button", { name: "Create task as agent" }).click();
  await expect(inspection.getByTestId("agent-action-result")).toContainText("forbidden");
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await expect(page.getByTestId("task-row").filter({ hasText: `${unique} denied` })).toHaveCount(0);

  await page.getByRole("button", { name: /^Agents/ }).click();
  await page.getByLabel("Agent name").fill(`${unique} writer`);
  await page.getByLabel("tasks:write", { exact: true }).check();
  await page.getByLabel("Personal tasks", { exact: true }).check();
  await page.getByRole("button", { name: "Create agent", exact: true }).click();
  const writer = page.getByTestId("agent-row").filter({ hasText: `${unique} writer` });
  await writer.getByRole("button", { name: "Inspect access" }).click();
  await inspection.getByLabel("Agent task title").fill(`${unique} allowed`);
  await inspection.getByRole("button", { name: "Create task as agent" }).click();
  await expect(inspection.getByTestId("agent-action-result")).toContainText("Allowed:");
  await expect(inspection.getByTestId("agent-counts")).toContainText("0 messages");
  await expect(inspection).toContainText(`Task: ${unique} allowed`);
  await page.screenshot({ path: testInfo.outputPath("workspace-agent-actions.png"), fullPage: true });
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await expect(page.getByTestId("task-row").filter({ hasText: `${unique} allowed` })).toHaveCount(1);
  await page.getByRole("button", { name: /^Agents/ }).click();
  await writer.getByRole("button", { name: "Inspect access" }).click();
  await writer.getByRole("button", { name: "Revoke", exact: true }).click();
  await expect(writer).toContainText("Revoked");
  await expect(inspection).toContainText("Effective scopes: none");
  await expect(inspection.getByRole("alert")).toContainText("unauthorized");
  await inspection.getByLabel("Agent task title").fill(`${unique} revoked`);
  await inspection.getByRole("button", { name: "Create task as agent" }).click();
  await expect(inspection.getByTestId("agent-action-result")).toContainText("unauthorized");
  await page.getByLabel("Fixture owner").selectOption("demo_sam");
  await page.getByRole("button", { name: /^Agents/ }).click();
  await expect(page.getByTestId("agent-row").filter({ hasText: unique })).toHaveCount(0);
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await expect(page.getByTestId("task-row").filter({ hasText: unique })).toHaveCount(0);
  await page.getByLabel("Fixture owner").selectOption("demo_alex");
  await page.getByRole("button", { name: /^Tasks/ }).click();
  await expect(page.getByTestId("task-row").filter({ hasText: `${unique} allowed` })).toHaveCount(1);
  await expect(page.getByTestId("task-row").filter({ hasText: `${unique} revoked` })).toHaveCount(0);
});
